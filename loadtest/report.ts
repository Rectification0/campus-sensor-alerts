// Pass/fail evaluation and Markdown rendering for the load test (T7.4).

import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import type { Mode, Summary } from '../simulator/sender.js';

export interface Scenario {
  id: string;
  title: string;
  mode: Mode;
  batchSize: number;
  connections: number;
}

/** Measured inside the server by loadtest/probe.mjs over one burst. */
export interface ServerUsage {
  avgCpuPercent: number; // CPU time / wall time; 100% = one core (includes GC and libuv threads)
  eventLoopUtilizationPercent: number; // share of the burst the JS thread was busy
  eventLoopDelayMaxMs: number;
  peakMemoryMb: number; // RSS
}

export interface RunResult {
  scenario: string;
  run: number;
  summary: Summary;
  rowsAdded: number;
  alertTriggersAdded: number;
  server: ServerUsage;
  pass: boolean;
  failures: string[];
}

export interface LoadTestData {
  generatedAt: string;
  command: string;
  machine: Record<string, string | number>;
  setup: {
    readingsPerBurst: number;
    sensors: number;
    types: string[];
    rules: number;
    runsPerScenario: number;
    server: Record<string, number>;
  };
  scenarios: Scenario[];
  results: RunResult[];
}

// specs §7 pass criteria + NFR-2 latency targets.
export const COMPLETION_LIMIT_MS = 3000; // FR-3.2
export const P99_LIMIT_MS = { batch: 1000, single: 2000 } as const; // NFR-2

export function evaluateRun(
  r: Omit<RunResult, 'pass' | 'failures'>,
  scenario: Scenario,
): RunResult {
  const s = r.summary;
  const failures: string[] = [];
  const non202 = s.requests - (s.statusCounts['202'] ?? 0);
  if (non202 > 0 || s.accepted !== s.readingsSent) {
    failures.push(`FR-3.1: ${non202} failed requests (${JSON.stringify(s.statusCounts)})`);
  }
  if (s.durationMs > COMPLETION_LIMIT_MS) {
    failures.push(`FR-3.2: completed in ${s.durationMs} ms > ${COMPLETION_LIMIT_MS} ms`);
  }
  if (r.rowsAdded !== s.accepted) {
    failures.push(`rows added ${r.rowsAdded} != accepted ${s.accepted}`);
  }
  const p99Limit = P99_LIMIT_MS[scenario.mode];
  if (s.latencyMs.p99 > p99Limit) {
    failures.push(`NFR-2: p99 ${s.latencyMs.p99} ms > ${p99Limit} ms`);
  }
  return { ...r, pass: failures.length === 0, failures };
}

const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid]! : (s[mid - 1]! + s[mid]!) / 2;
};
const fmt = (n: number) => (Number.isInteger(n) ? n.toLocaleString('en-US') : n.toFixed(1));

function table(header: string[], rows: (string | number)[][]): string {
  const line = (cells: (string | number)[]) =>
    `| ${cells.map((c) => (typeof c === 'number' ? fmt(c) : c)).join(' | ')} |`;
  return [line(header), `|${header.map(() => '---').join('|')}|`, ...rows.map(line)].join('\n');
}

export function renderResults(data: LoadTestData): string {
  const out: string[] = [];
  const m = data.machine;
  const srv = data.setup.server;

  out.push(
    `_Generated by \`${data.command}\` at ${data.generatedAt}. Raw data: [\`load-test-results.json\`](load-test-results.json)._`,
    '',
    '## Environment',
    '',
    table(
      ['Item', 'Value'],
      [
        ['CPU', `${m.cpu} (${m.logicalCores} logical cores)`],
        ['Memory', `${m.memoryGb} GB`],
        ['OS', String(m.os)],
        ['Node.js', String(m.node)],
        ['Database', String(m.postgres)],
        [
          'Server settings',
          Object.entries(srv)
            .map(([k, v]) => `\`${k}=${v}\``)
            .join(', '),
        ],
      ],
    ),
    '',
    '## Method',
    '',
    `- **Burst:** ${fmt(data.setup.readingsPerBurst)} readings from ${data.setup.sensors} sensors × ${data.setup.types.length} types (${data.setup.types.join(', ')}), generated up front and dispatched at once by the project's simulator (\`runBurst\`, undici keep-alive pool). The client runs on the same machine as the server and the database.`,
    `- **Rules:** ${data.setup.rules} enabled rules (THRESHOLD and WINDOW, per \`loadtest/seed-rules.ts\`), some of which fire on normal data, so rule evaluation and alert upserts are part of the measured cost.`,
    `- **Server:** production build (\`dist/server.js\`), request logging off, against a freshly migrated dedicated database. A warm-up burst (excluded) runs first.`,
    `- **Runs:** ${data.setup.runsPerScenario} per scenario, 1 s apart.`,
    '- **Completion time:** from the first request to the last response. Every `202` is sent only after the reading is committed, so this is also time-to-persisted.',
    '- **Latency:** per HTTP request, from send to full response.',
    '- **Server usage:** measured inside the server by a probe preloaded only for the load test (`loadtest/probe.mjs`, reporting over IPC, so sampling launches no processes). CPU = CPU time ÷ wall time (100% = one core); event-loop busy = share of the burst the JavaScript thread was working; RSS = peak resident memory.',
    '- **DB check:** rows added to `readings` during the run must equal readings accepted.',
    '',
    '## Results',
    '',
    `Pass criteria: no failed requests (FR-3.1), last response within ${fmt(COMPLETION_LIMIT_MS)} ms of the burst start (FR-3.2), DB rows = accepted readings (specs §7), and request p99 below ${fmt(P99_LIMIT_MS.batch)} ms for batches / ${fmt(P99_LIMIT_MS.single)} ms for single readings (NFR-2).`,
    '',
  );

  const summaryRows: (string | number)[][] = [];
  for (const sc of data.scenarios) {
    const runs = data.results.filter((r) => r.scenario === sc.id);
    const d = runs.map((r) => r.summary.durationMs);
    const p99 = runs.map((r) => r.summary.latencyMs.p99);
    summaryRows.push([
      `**${sc.id}** ${sc.title}`,
      `${fmt(median(d))} / ${fmt(Math.max(...d))}`,
      `${fmt(median(p99))} / ${fmt(Math.max(...p99))}`,
      Math.min(...runs.map((r) => r.summary.accepted)),
      runs.reduce((a, r) => a + (r.summary.requests - (r.summary.statusCounts['202'] ?? 0)), 0),
      runs.every((r) => r.rowsAdded === r.summary.accepted) ? 'yes' : 'NO',
      runs.every((r) => r.pass) ? '**PASS**' : '**FAIL**',
    ]);
  }
  out.push(
    table(
      [
        'Scenario',
        'Completion ms (median / worst)',
        'p99 ms (median / worst)',
        'Min accepted',
        'Failed requests',
        'DB rows match',
        'Result',
      ],
      summaryRows,
    ),
    '',
  );

  for (const sc of data.scenarios) {
    const runs = data.results.filter((r) => r.scenario === sc.id);
    out.push(
      `### ${sc.id}: ${sc.title}`,
      '',
      `Mode \`${sc.mode}\`${sc.mode === 'batch' ? `, ${sc.batchSize} readings per request` : ''}, ${fmt(runs[0]?.summary.requests ?? 0)} requests over ${fmt(sc.connections)} client connections.`,
      '',
      table(
        [
          'Run',
          'Completion ms',
          'Readings/s',
          'p50 ms',
          'p95 ms',
          'p99 ms',
          'max ms',
          'Statuses',
          'Rows added',
          'Alert triggers',
          'Server CPU %',
          'Event loop busy %',
          'Max loop delay ms',
          'Server RSS MB',
          'Result',
        ],
        runs.map((r) => [
          r.run,
          r.summary.durationMs,
          r.summary.readingsPerSecond,
          r.summary.latencyMs.p50,
          r.summary.latencyMs.p95,
          r.summary.latencyMs.p99,
          r.summary.latencyMs.max,
          Object.entries(r.summary.statusCounts)
            .map(([k, v]) => `${k}×${fmt(v)}`)
            .join(', '),
          r.rowsAdded,
          r.alertTriggersAdded,
          r.server.avgCpuPercent,
          r.server.eventLoopUtilizationPercent,
          r.server.eventLoopDelayMaxMs,
          r.server.peakMemoryMb,
          r.pass ? 'pass' : `FAIL: ${r.failures.join('; ')}`,
        ]),
      ),
      '',
    );
  }
  return out.join('\n');
}

const START = '<!-- results:start (generated by pnpm loadtest; edits here are overwritten) -->';
const END = '<!-- results:end -->';

/** Replaces the generated section, keeping hand-written text around it. */
export async function writeReport(path: string, data: LoadTestData): Promise<void> {
  const generated = `${START}\n${renderResults(data)}\n${END}`;
  let doc: string;
  if (existsSync(path)) {
    const current = await readFile(path, 'utf8');
    const a = current.indexOf(START);
    const b = current.indexOf(END);
    doc =
      a >= 0 && b > a
        ? current.slice(0, a) + generated + current.slice(b + END.length)
        : `${current.trimEnd()}\n\n${generated}\n`;
  } else {
    doc = `# Load-test report: 10,000 readings in one second\n\n${generated}\n\n## Analysis\n\n_To be written after reviewing the results._\n`;
  }
  await writeFile(path, doc);
}
